CREATE TABLE profile_profiles
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email      VARCHAR(255)             NOT NULL UNIQUE,
    status     VARCHAR(50)              NOT NULL
        CHECK (status IN ('PENDING', 'ACTIVE', 'SUSPENDED')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE profile_publishers
(
    id         BIGINT PRIMARY KEY,
    first_name VARCHAR(255) NOT NULL,
    last_name  VARCHAR(255) NOT NULL,
    niche      VARCHAR(50)  NOT NULL
        CHECK (niche IN (
                         'BEAUTY', 'TECH', 'GAMING',
                         'TRAVEL', 'LIFESTYLE', 'FOOD', 'SPORT'
            )),
    bio        TEXT,
    country    VARCHAR(255),

    CONSTRAINT fk_profile_publishers_profile
        FOREIGN KEY (id)
            REFERENCES profile_profiles (id)
);

CREATE TABLE profile_advertisers
(
    id           BIGINT PRIMARY KEY,
    company_name VARCHAR(255) NOT NULL,
    sector       VARCHAR(255) NOT NULL,
    website      VARCHAR(255) NOT NULL,

    CONSTRAINT fk_profile_advertisers_profile
        FOREIGN KEY (id)
            REFERENCES profile_profiles (id)
);
