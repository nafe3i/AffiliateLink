
-- ==========================================================
-- V3 - Module Offre : Offre, Campagne, Tag
-- ==========================================================

-- 1. OFFRES
CREATE TABLE offre_offres
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    advertiser_id BIGINT NOT NULL,

    title VARCHAR(255) NOT NULL,
    description TEXT,
    landing_url VARCHAR(255) NOT NULL,

    niche VARCHAR(255) NOT NULL,

    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);


-- 2. TAGS
CREATE TABLE offre_tags
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    name VARCHAR(255) NOT NULL,

    CONSTRAINT uk_offre_tags_name
        UNIQUE (name),

    CONSTRAINT ck_offre_tags_name
        CHECK (
            name <> ''
                AND name = btrim(name)
                AND name = lower(name)
            )
);


-- 3. CAMPAGNES
CREATE TABLE offre_campagnes
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    name VARCHAR(255) NOT NULL,

    start_date DATE NOT NULL,
    end_date DATE NOT NULL,

    budget NUMERIC(14, 2) NOT NULL,

    payout_model VARCHAR(255) NOT NULL,
    payout_value NUMERIC(14, 2) NOT NULL,

    status VARCHAR(255) NOT NULL DEFAULT 'DRAFT',

    offre_id BIGINT NOT NULL,

    CONSTRAINT fk_campagne_offre
        FOREIGN KEY (offre_id)
            REFERENCES offre_offres(id),

    CONSTRAINT ck_campagne_dates
        CHECK (end_date > start_date),

    CONSTRAINT ck_campagne_budget
        CHECK (budget > 0),

    CONSTRAINT ck_campagne_payout_model
        CHECK (
            payout_model IN (
                             'CPC',
                             'CPL',
                             'CPA_FIXED',
                             'CPA_PERCENT'
                )
            ),

    CONSTRAINT ck_campagne_payout_value
        CHECK (
            payout_value > 0
                AND (
                payout_model <> 'CPA_PERCENT'
                    OR payout_value < 100
                )
            ),

    CONSTRAINT ck_campagne_status
        CHECK (
            status IN (
                       'DRAFT',
                       'ACTIVE',
                       'PAUSED',
                       'ENDED'
                )
            )
);


-- 4. RELATION OFFRE <-> TAG
CREATE TABLE offre_offres_tags
(
    offre_id BIGINT NOT NULL,
    tag_id BIGINT NOT NULL,

    CONSTRAINT pk_offre_offres_tags
        PRIMARY KEY (offre_id, tag_id),

    CONSTRAINT fk_offres_tags_offre
        FOREIGN KEY (offre_id)
            REFERENCES offre_offres(id),

    CONSTRAINT fk_offres_tags_tag
        FOREIGN KEY (tag_id)
            REFERENCES offre_tags(id)
);


-- 5. INDEX POUR LES RECHERCHES ET RELATIONS
CREATE INDEX idx_offre_offres_advertiser
    ON offre_offres(advertiser_id);

CREATE INDEX idx_offre_offres_niche
    ON offre_offres(niche);

CREATE INDEX idx_offre_campagnes_offre
    ON offre_campagnes(offre_id);

CREATE INDEX idx_offre_campagnes_status
    ON offre_campagnes(status);

CREATE INDEX idx_offres_tags_tag
    ON offre_offres_tags(tag_id);
